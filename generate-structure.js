#!/usr/bin/env node
import fs from 'fs';
import path from 'path';

const OUTPUT_FILE = 'PROJECT_STRUCTURE.md';
const EXCLUDE_DIRS = ['node_modules', 'dist', '.git', '.vscode'];

/**
 * Recursively build a Markdown tree of the folder.
 */
function buildTree(dir, prefix = '') {
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !EXCLUDE_DIRS.includes(entry.name))
    .sort((a, b) => a.name.localeCompare(b.name));

  let tree = '';

  entries.forEach((entry, index) => {
    const isLast = index === entries.length - 1;
    const connector = isLast ? '└── ' : '├── ';
    const nextPrefix = prefix + (isLast ? '    ' : '│   ');

    tree += `${prefix}${connector}${entry.name}\n`;

    if (entry.isDirectory()) {
      tree += buildTree(path.join(dir, entry.name), nextPrefix);
    }
  });

  return tree;
}

/**
 * Generate the Markdown documentation.
 */
function generateMarkdownStructure() {
  const rootDir = process.cwd();
  const tree = buildTree(rootDir);

  const markdown = `# 📁 Project Structure

> Generated automatically on **${new Date().toLocaleString()}**

\`\`\`
${tree}
\`\`\`

---

### 🧩 Notes
- Auto-generated by \`generate-structure.js\`
- Excluded folders: \`${EXCLUDE_DIRS.join(', ')}\`
`;

  fs.writeFileSync(OUTPUT_FILE, markdown, 'utf8');
  console.log(`✅ Markdown structure generated at ./${OUTPUT_FILE}`);
}

// Run it
generateMarkdownStructure();
